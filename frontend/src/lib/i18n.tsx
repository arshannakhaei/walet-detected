export type Lang = 'fa' | 'en'
const DICTS: Record<Lang, Dict> = { fa, en }

interface I18n {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: TKey) => string
  dir: 'rtl' | 'ltr'
}

const Ctx = createContext<I18n | null>(null)

function initialLang(): Lang {
  try {
    return localStorage.getItem('ct-lang') === 'en' ? 'en' : 'fa'
  } catch {
    return 'fa'
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const dir: 'rtl' | 'ltr' = lang === 'fa' ? 'rtl' : 'ltr'

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = dir
  }, [lang, dir])

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem('ct-lang', l)
    } catch {
      /* storage unavailable */
    }
  }, [])

  const value = useMemo(() => ({ lang, setLang, dir, t: (k: TKey) => DICTS[lang][k] }), [lang, setLang, dir])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n outside provider')
  return ctx
}
